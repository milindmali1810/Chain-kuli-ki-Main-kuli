// Fills players.role from what each player actually did.
// Runs outside Vercel:  npm run infer:roles -- [--before 2026-10-06]
//   --before  only use matches strictly before this date (default: today). Use the demo match date
//             for the backtest so the demo match cannot leak into the roles.

import { createClient } from "@supabase/supabase-js";
import { ROLE_INFERENCE } from "../src/config/roleInference";
import { inferRole, type StatsNoRole } from "../src/lib/inferRole";

const args = process.argv.slice(2);
const i = args.indexOf("--before");
const before = i >= 0 ? args[i + 1] : new Date().toISOString().slice(0, 10);

const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
if (!url || !key) throw new Error("Missing Supabase settings in .env.local");
const db = createClient(url, key, { auth: { persistSession: false } });

const from = new Date(before);
from.setMonth(from.getMonth() - ROLE_INFERENCE.windowMonths.value);
const fromDate = from.toISOString().slice(0, 10);

async function main() {
  console.log(`Using matches from ${fromDate} up to (not including) ${before}`);

  // All stats rows in the window, grouped by player.
  const byPlayer = new Map<number, StatsNoRole[]>();
  for (let start = 0; ; start += 1000) {
    const { data, error } = await db
      .from("player_match_lines")
      .select("player_id, stats_json, matches!inner(start_time)")
      .gte("matches.start_time", `${fromDate}T00:00:00Z`)
      .lt("matches.start_time", `${before}T00:00:00Z`)
      .order("match_id")
      .order("player_id")
      .range(start, start + 999);
    if (error) throw new Error(error.message);
    for (const row of data) {
      const list = byPlayer.get(row.player_id) ?? [];
      list.push(row.stats_json as StatsNoRole);
      byPlayer.set(row.player_id, list);
    }
    if (data.length < 1000) break;
  }
  console.log(`Read stats for ${byPlayer.size} players`);

  // All players (so people with no data in the window get their role cleared, not left stale).
  const players: { id: number; cricsheet_id: string; name: string; source_flags: Record<string, unknown> }[] = [];
  for (let start = 0; ; start += 1000) {
    const { data, error } = await db.from("players").select("id,cricsheet_id,name,source_flags").order("id").range(start, start + 999);
    if (error) throw new Error(error.message);
    players.push(...data);
    if (data.length < 1000) break;
  }

  const counts: Record<string, number> = {};
  const updates = players.map((p) => {
    const role = inferRole(byPlayer.get(p.id) ?? []);
    counts[role ?? "unavailable"] = (counts[role ?? "unavailable"] ?? 0) + 1;
    // "id" is generated by the database and cannot be sent, so players are matched on cricsheet_id.
    return { cricsheet_id: p.cricsheet_id, name: p.name, role, source_flags: { ...p.source_flags, role_origin: "inferred", role_as_of: before } };
  });

  for (let s = 0; s < updates.length; s += 500) {
    const { error } = await db.from("players").upsert(updates.slice(s, s + 500), { onConflict: "cricsheet_id" });
    if (error) throw new Error(error.message);
  }
  console.log("Roles written:", counts);
}

main().catch((e) => {
  console.error("FAILED:", e instanceof Error ? e.message : e);
  process.exit(1);
});
